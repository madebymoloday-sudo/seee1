export function getOrgRoleProfile(nodeId: string, title: string): OrgRoleProfile {
  if (specificProfiles[nodeId]) {
    return specificProfiles[nodeId];
  }

  if (title.includes("Департамент")) {
    return genericDepartmentProfile(title);
  }

  return genericSectionProfile(title);
}

export function flattenOrgNodes(node: TeamOrgNode): TeamOrgNode[] {
  return [node, ...(node.children?.flatMap(flattenOrgNodes) ?? [])];
}
